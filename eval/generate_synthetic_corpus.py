def main() -> None:
    rng = random.Random(SEED)

    catalog = build_merchant_catalog(rng)

    # Attach surface-text variants (deterministic — driven by the same
    # seeded rng, iterating categories/merchants in FIXED order so output
    # is reproducible regardless of dict iteration nuances).
    for cat in DEFAULT_CATEGORIES:
        for merchant in catalog[cat]:
            merchant["variants"] = make_variants(merchant["base_name"], rng)
            assert_variant_bucket_consistency(merchant, merchant["variants"])

    # Global merchant_id uniqueness (belt-and-suspenders — build_merchant_
    # catalog already enforces this, but re-check post-hoc across the
    # flattened catalog).
    all_ids = [m["merchant_id"] for cat in DEFAULT_CATEGORIES for m in catalog[cat]]
    assert len(all_ids) == len(set(all_ids)), "duplicate merchant_id in catalog"
    normalized = [mid.strip().lower() for mid in all_ids]
    assert len(normalized) == len(set(normalized)), "near-duplicate merchant_id spellings in catalog"

    recurring_plan = assign_recurring_merchants(catalog, rng)

    row_counter: dict[str, int] = {}
    all_rows: list[dict] = []
    per_archetype_counts: dict[str, int] = {}

    for archetype_id in ARCHETYPES:  # dict insertion order — fixed, deterministic
        archetype = ARCHETYPES[archetype_id]
        rows = simulate_archetype(archetype_id, archetype, catalog, recurring_plan, rng, row_counter)
        all_rows.extend(rows)
        per_archetype_counts[archetype_id] = len(rows)

    # Global row id uniqueness.
    row_ids = [r["id"] for r in all_rows]
    assert len(row_ids) == len(set(row_ids)), "duplicate row id generated"

    # Final zero-tolerance sweep over every emitted row.
    for r in all_rows:
        assert_row_is_clean(r["merchant_text"])
        assert r["category"] in DEFAULT_CATEGORIES

    total_merchants = len(all_ids)
    total_rows = len(all_rows)

    out_path = Path(__file__).parent / "categorization_corpus.synthetic_multi_archetype.jsonl"
    header = HEADER.format(
        seed=SEED,
        total_rows=total_rows,
        total_merchants=total_merchants,
        n_archetypes=len(ARCHETYPES),
    )
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(header)
        for r in all_rows:
            f.write(json.dumps(r, sort_keys=True, ensure_ascii=False))
            f.write("\n")

    # ── Stats ────────────────────────────────────────────────────────
    print(f"wrote {out_path} ({total_rows} rows, {total_merchants} unique merchants)")
    print("\nper-archetype row counts:")
    for aid, n in per_archetype_counts.items():
        print(f"  {aid:<32} {n}")

    print("\nper-category row counts:")
    cat_row_counts: dict[str, int] = {}
    for r in all_rows:
        cat_row_counts[r["category"]] = cat_row_counts.get(r["category"], 0) + 1
    for cat in DEFAULT_CATEGORIES:
        print(f"  {cat:<15} {cat_row_counts.get(cat, 0)}")

    print("\nper-category unique-merchant counts + declared vs measured hit ratio:")
    for cat in DEFAULT_CATEGORIES:
        merchants = catalog[cat]
        n_hit = sum(1 for m in merchants if m["bucket"] == "hit")
        n_total = len(merchants)
        declared = CATEGORY_CONFIG[cat]["declared_hit_ratio"]
        measured_merchant = n_hit / n_total if n_total else 0.0
        rows_in_cat = [r for r in all_rows if r["category"] == cat]
        n_hit_rows = sum(1 for r in rows_in_cat if r["notes"].startswith("keyword-hit"))
        measured_row = n_hit_rows / len(rows_in_cat) if rows_in_cat else 0.0
        print(
            f"  {cat:<15} merchants={n_total:>3} (hit={n_hit:>3})  "
            f"declared={declared:.0%}  measured(merchant)={measured_merchant:.1%}  "
            f"measured(row)={measured_row:.1%}"
        )


if __name__ == "__main__":
    main()
