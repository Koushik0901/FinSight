class MerchantCatalogError(RuntimeError):
    pass


def build_merchant_catalog(rng: random.Random) -> dict[str, list[dict]]:
    """Build the shared, cross-archetype merchant catalog.

    Every merchant's `bucket` ("hit" | "nohit") is VERIFIED against the
    KEYWORD_MAP mirror at build time — a candidate name that doesn't
    resolve to the expected category (or None, for nohit) is rejected and
    another prefix is tried. `merchant_id` uniqueness is enforced globally
    (across ALL categories, not just within one), because the near-
    duplicate check in `crates/finsight-eval/src/categorization/corpus.rs
    ::validate_corpus` operates on the whole file.
    """
    used_slugs: set[str] = set()
    used_base_names: set[str] = set()
    catalog: dict[str, list[dict]] = {}

    for cat in DEFAULT_CATEGORIES:
        cfg = CATEGORY_CONFIG[cat]
        target = cfg["target_count"]
        hit_target = round(target * cfg["declared_hit_ratio"])
        nohit_target = target - hit_target

        merchants: list[dict] = []

        def try_fill(bucket: str, suffixes: list[str], count: int) -> None:
            if count == 0:
                return
            prefixes_shuffled = PREFIXES[:]
            rng.shuffle(prefixes_shuffled)
            suffixes_shuffled = suffixes[:]
            rng.shuffle(suffixes_shuffled)
            found = 0
            attempts = 0
            max_attempts = len(prefixes_shuffled) * len(suffixes_shuffled) * 3
            pi = 0
            si = 0
            while found < count:
                attempts += 1
                if attempts > max_attempts:
                    raise MerchantCatalogError(
                        f"could not find {count} unique {bucket} merchants for "
                        f"category {cat!r} after {attempts} attempts "
                        f"(found {found}) — widen the prefix/suffix pool"
                    )
                prefix = prefixes_shuffled[pi % len(prefixes_shuffled)]
                suffix = suffixes_shuffled[si % len(suffixes_shuffled)]
                pi += 1
                if pi % len(prefixes_shuffled) == 0:
                    si += 1
                base_name = f"{prefix} {suffix}"
                if base_name in used_base_names:
                    continue
                predicted = builtin_category(base_name)
                if bucket == "hit":
                    if predicted != cat:
                        continue
                else:
                    if predicted is not None:
                        continue
                slug = f"m-{slugify(base_name)}"
                if slug in used_slugs:
                    continue
                assert_row_is_clean(base_name)
                used_base_names.add(base_name)
                used_slugs.add(slug)
                merchants.append(
                    {
                        "merchant_id": slug,
                        "base_name": base_name,
                        "category": cat,
                        "bucket": bucket,
                        "needle": first_matching_needle(base_name) if bucket == "hit" else None,
                    }
                )
                found += 1

        try_fill("hit", cfg["hit_suffixes"], hit_target)
        try_fill("nohit", cfg["nohit_suffixes"], nohit_target)

        catalog[cat] = merchants

    return catalog


