def builtin_category(text: str) -> str | None:
    """Python mirror of `finsight_core::categorize::builtin_category`."""
    m = text.lower()
    for needle, cat in KEYWORD_MAP:
        if needle in m:
            return cat
    return None


def first_matching_needle(text: str) -> str | None:
    m = text.lower()
    for needle, _cat in KEYWORD_MAP:
        if needle in m:
            return needle
    return None


