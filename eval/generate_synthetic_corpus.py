# Surface-text variant generation
#
# Multiple realistic raw-description VARIANTS share one merchant_id, per
# the task's explicit stress-test goal for `validate_corpus`'s near-
# duplicate detection and the split's disjointness guarantee at real
# scale. Every variant is constructed by concatenating (never truncating
# or rewriting internal characters of) `base_name` or its uppercase form,
# so a "hit" merchant's KEYWORD_MAP substring survives in every variant —
# verified, not just assumed (see `assert_variant_bucket_consistency`).
# ═══════════════════════════════════════════════════════════════════════


def make_variants(base_name: str, rng: random.Random) -> list[str]:
    variants: set[str] = set()
    variants.add(base_name)
    upper = base_name.upper()
    variants.add(upper)

    store_num = rng.randint(100, 9999)
    variants.add(f"{base_name} #{store_num}")
    variants.add(f"{upper} #{store_num:04d}")

    city, prov = rng.choice(CITIES)
    variants.add(f"{base_name} - {city} {prov}")
    variants.add(f"{upper} {city.upper()} {prov}")

    variants.add(f"POS PURCHASE {upper}")

    ref = rng.randint(100000, 999999)
    variants.add(f"{base_name} REF{ref}")

    if "&" in base_name:
        variants.add(base_name.replace("&", "AND"))
    if "'" in base_name:
        variants.add(base_name.replace("'", ""))

    for v in variants:
        assert_row_is_clean(v)

    return sorted(variants)


def assert_variant_bucket_consistency(merchant: dict, variants: list[str]) -> None:
    cat = merchant["category"]
    bucket = merchant["bucket"]
    for v in variants:
        predicted = builtin_category(v)
        if bucket == "hit":
            assert predicted == cat, (
                f"hit-bucket merchant {merchant['merchant_id']!r} variant "
                f"{v!r} predicted {predicted!r}, expected {cat!r}"
            )
        else:
            assert predicted is None, (
                f"nohit-bucket merchant {merchant['merchant_id']!r} variant "
                f"{v!r} unexpectedly matched KEYWORD_MAP category {predicted!r}"
            )


