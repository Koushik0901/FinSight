#!/usr/bin/env python3
"""Generator for eval/categorization_corpus.synthetic_multi_archetype.jsonl.

Extends the labeled-corpus work from issue #89 ("[Slice 2b] Labeled
merchant-diverse transaction corpus + merchant-disjoint split") WITHOUT
claiming to close it. #89's actual acceptance criteria require REAL labeled
data (human ground truth). This script produces none of that — it produces a
much wider, more realistic SYNTHETIC corpus that stress-tests the
categorization eval harness (crates/finsight-eval/src/categorization/) at
real scale (thousands of rows, hundreds of merchants, many raw-text
variants per merchant), which the original 33-row hand-curated seed
(eval/categorization_corpus.synthetic.jsonl, NOT touched by this script) is
too small to meaningfully exercise.

READ THIS TWICE: every merchant name below is INVENTED. None of it is drawn
from, inspired by the specific content of, or derived from any real user's
account data or any real company. Structural/formatting conventions (store
numbers, "POS PURCHASE" tags, city+province suffixes, trailing reference
digits) are common public knowledge of how bank and card statements format
transaction descriptors generally — not specific to any one account or
institution. This corpus DOES NOT satisfy issue #89's real-data requirement
and must never be presented as if it did. Say it again: THIS IS SYNTHETIC
DATA, not a real-world precision benchmark, no matter how large it is.

## Methodology inspiration (not a data source)

The archetype-weighted category/amount-distribution design below draws its
general APPROACH from `namebrandon/Sparkov_Data_Generation`
(https://github.com/namebrandon/Sparkov_Data_Generation, MIT licensed) — a
well-established synthetic transaction generator that assigns each simulated
"customer" a demographic profile with weighted category distributions and
per-category amount distributions. We cite it as prior art for *how to
structure* a multi-persona synthetic generator. We do NOT import its data,
its merchant list (Faker.company()-generated generic names, not the noisy
real-bank-statement-style text this corpus needs), or its category taxonomy
(16 categories that don't map onto FinSight's 10 starter categories). Every
merchant name, archetype, and word bank here is this script's own invention.

## Explicit exclusions (do not "fix" these by adding rows later)

- NO transfer-shaped rows: no E-TRANSFER, INTERNET TRANSFER, PAYMENT THANK
  YOU, AUTOPAY, or any descriptor that would trip
  `finsight_core::categorize::is_transfer`. Transfers are never categorized
  by this product (see that function + `apply_builtin_categorization`'s
  `if treat_as_transfer { continue; }`), so a transfer-shaped row would
  misrepresent what this corpus is testing: category ground truth.
- NO investment/brokerage-shaped rows (dividends, trades, brokerage
  statements). FinSight routes those through `activity_type`, a field this
  flat labeled-corpus format does not have (see predictors.rs's documented
  fidelity gap), and this generator does not attempt to model it.
- Both exclusions are enforced programmatically below (`assert_row_is_clean`)
  — a build that produces a violating row raises, it does not silently ship.

## Determinism

`SEED` below is a fixed constant. Re-running this script with an unchanged
SEED and unchanged code produces byte-identical output (all iteration is
over sorted/fixed-order structures, all randomness flows through one seeded
`random.Random` instance — never the `random` module's global state). This
is a checked-in static artifact, not something regenerated by `cargo test`.

## Keyword-hit ratio: declared per category, not organic

We do NOT let invented names organically end up containing
`finsight_core::categorize::KEYWORD_MAP` substrings by chance of word
choice — that would make measured `builtin` precision on this corpus a
property of naming taste, not of the keyword table, the exact circularity a
prior review flagged for the small seed's `rule`-source 100% precision.
Instead every merchant is generated into an explicit "hit" or "no-hit"
bucket (see `CATEGORY_CONFIG[cat]["declared_hit_ratio"]`), verified against
a literal Python mirror of the real `KEYWORD_MAP` (kept in the SAME order —
first match wins, exactly like the Rust code), and every row's `notes` field
says which bucket its merchant belongs to.

Several categories are declared at or near 0% hit rate NOT as an oversight
but because their real KEYWORD_MAP entries are (almost) exclusively real,
specific company brand names (Walmart, Costco, Amazon, Best Buy, Telus,
Netflix, ...) which this corpus's "never real brand names" rule (see
`eval/CATEGORIZATION_CORPUS.md`) forbids reproducing:
  - groceries: EVERY KEYWORD_MAP groceries entry is a specific real grocery
    chain (walmart, safeway, costco, ... down to "t&t supermarket"). There
    is no generic groceries word to embed. Declared hit ratio: 0%.
  - shopping: same story (amazon, best buy, ikea, home depot, ...). 0%.
  - subscriptions: almost entirely specific SaaS/streaming brands
    (netflix, spotify, adobe, ...), with exactly one generic phrase,
    "membership fee". Declared hit ratio: ~15%, sourced only from that
    phrase.
  - travel: almost entirely specific airline/hotel/OTA brands, with one
    generic French common noun for "inn", "auberge". Declared hit ratio:
    ~10%, sourced only from that word.
  - gifts: the REAL KEYWORD_MAP has literally zero entries mapping to
    "gifts" (see the existing seed's `gf1` note, which already documents
    this). Declared hit ratio: 0% — structurally forced, not a choice.
Categories with generic, non-brand keyword vocabulary (dining: pizza,
burger, sushi, bakery, cafe, coffee, donut, restaurant; transport: parking,
transit; housing: mortgage, property mgmt/management, " rent "; utilities:
hydro; health: pharmacy, dental, clinic, physio) get a meaningfully higher
declared hit ratio, because those words are genuinely generic business
descriptors, not brand names.

This is checked twice: once here (generation-time, against the Python
mirror) and again in a Rust test (`crates/finsight-eval/src/categorization/
multi_archetype.rs`) that calls the REAL `finsight_core::categorize::
builtin_category` and asserts the measured per-category rate lands within
tolerance of the declared target — so if this Python mirror ever drifts out
of sync with the real KEYWORD_MAP, that Rust test is what catches it.
"""

