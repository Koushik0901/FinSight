def assert_row_is_clean(text: str) -> None:
    """Hard-fail generation if a row is transfer- or investment-shaped.

    Deliberately a SUPERSET check (every transfer/CC/investment substring
    forbidden outright, not just the exact `is_transfer` boolean formula)
    so this stays robust to the exact pairing/own-account-marker logic
    without having to re-derive it perfectly in Python.
    """
    lower = text.lower()
    for needle in _ALL_FORBIDDEN_SUBSTRINGS:
        if needle in lower:
            raise AssertionError(
                f"generated row text {text!r} contains forbidden vocabulary "
                f"{needle!r} (transfer/CC/investment) — this corpus must "
                f"contain zero transfer- or investment-shaped rows"
            )


