def seasonal_multiplier(archetype: dict, category: str, month: int) -> float:
    mult = 1.0
    for months, cat, m in archetype.get("seasonal", []):
        if cat == category and month in months:
            mult *= m
    return mult


def poisson_ish(rng: random.Random, mean: float) -> int:
    """Cheap Poisson-ish integer draw without numpy: Gaussian approximation
    (stdev = sqrt(mean)) clipped at 0. Good enough for corpus-scale
    realism; exact Poisson shape doesn't matter here since counts are
    never serialized as amounts/statistics, only as "how many rows."
    """
    if mean <= 0:
        return 0
    stdev = max(mean ** 0.5, 0.4)
    draw = rng.gauss(mean, stdev)
    return max(0, round(draw))


def assign_recurring_merchants(
    catalog: dict[str, list[dict]], rng: random.Random
) -> dict[str, dict[str, list[dict]]]:
    """Pick which merchants serve as each archetype's recurring bills, for
    every recurring-eligible category, via ONE global stratified draw per
    category rather than independent per-archetype sampling.

    Why: independent per-archetype `rng.sample` draws (the first version of
    this script did this) have two problems for categories with few total
    "recurring slots" (e.g. housing has only 6 slots — one per archetype
    that carries a mortgage/rent — across a pool of 10 merchants):
      1. Distinct-merchant diversity suffers from collisions (two
         archetypes independently landing on the same merchant), wasting
         pool size.
      2. The realized hit/no-hit split of the merchants that ACTUALLY get
         used can drift far from `declared_hit_ratio` — with only a
         handful of slots, ordinary sampling variance can flip a 55%
         declared target into something like 20% or 80% actually used,
         which would make the keyword-hit-ratio test either fail
         spuriously or need a tolerance so wide it stops checking anything.

    The fix: compute the TOTAL number of recurring slots a category needs
    across all archetypes, then draw that many DISTINCT merchants in one
    shot, stratified to match `declared_hit_ratio` as closely as integer
    rounding allows, with NO repeats (maximizing diversity, bounded by pool
    size). The resulting global draw is then partitioned across archetypes
    in fixed (dict-iteration) order — deterministic, and the actually-used
    merchant set's hit ratio is now a designed property again, not a
    sampling accident.
    """
    plan: dict[str, dict[str, list[dict]]] = {}
    for cat in DEFAULT_CATEGORIES:
        slots: list[tuple[str, int]] = []
        for arch_id, arch in ARCHETYPES.items():
            spec = arch.get("recurring", {}).get(cat)
            if spec:
                slots.append((arch_id, spec["count"]))
        total_slots = sum(c for _, c in slots)
        if total_slots == 0:
            continue

        pool = catalog[cat]
        hit_pool = [m for m in pool if m["bucket"] == "hit"]
        nohit_pool = [m for m in pool if m["bucket"] == "nohit"]
        declared_ratio = CATEGORY_CONFIG[cat]["declared_hit_ratio"]

        n_hit = min(round(total_slots * declared_ratio), len(hit_pool))
        n_nohit = total_slots - n_hit
        if n_nohit > len(nohit_pool):
            deficit = n_nohit - len(nohit_pool)
            n_nohit = len(nohit_pool)
            n_hit = min(n_hit + deficit, len(hit_pool))

        chosen = rng.sample(hit_pool, n_hit) + rng.sample(nohit_pool, n_nohit)
        rng.shuffle(chosen)

        if len(chosen) < total_slots:
            chosen_ids = {m["merchant_id"] for m in chosen}
            remaining = [m for m in pool if m["merchant_id"] not in chosen_ids]
            rng.shuffle(remaining)
            chosen.extend(remaining[: total_slots - len(chosen)])

        assert len(chosen) >= total_slots, (
            f"category {cat!r} pool of {len(pool)} cannot satisfy "
            f"{total_slots} recurring slots across all archetypes — "
            f"widen its CATEGORY_CONFIG target_count"
        )

        idx = 0
        per_archetype: dict[str, list[dict]] = {}
        for arch_id, count in slots:
            per_archetype[arch_id] = chosen[idx : idx + count]
            idx += count
        plan[cat] = per_archetype

    return plan


def simulate_archetype(
    archetype_id: str,
    archetype: dict,
    catalog: dict[str, list[dict]],
    recurring_plan: dict[str, dict[str, list[dict]]],
    rng: random.Random,
    row_counter: dict[str, int],
) -> list[dict]:
    rows: list[dict] = []

    def emit(merchant: dict, note_suffix: str) -> None:
        text = rng.choice(merchant["variants"])
        assert_row_is_clean(text)
        bucket = merchant["bucket"]
        if bucket == "hit":
            note = f"keyword-hit by design (matches KEYWORD_MAP {merchant['needle']!r})"
        else:
            note = "no builtin keyword overlap by design — coverage gap"
        note = f"{note} | archetype: {archetype_id}{note_suffix}"
        cat = merchant["category"]
        row_counter[cat] = row_counter.get(cat, 0) + 1
        row_id = f"{archetype_id}-{cat}-{row_counter[cat]:04d}"
        rows.append(
            {
                "id": row_id,
                "merchant_text": text,
                "merchant_id": merchant["merchant_id"],
                "category": cat,
                "notes": note,
            }
        )

    # Recurring: merchants were already chosen for this archetype+category
    # by the global stratified draw in `assign_recurring_merchants` (see
    # its docstring for why that beats per-archetype independent sampling).
    # Emit ONE row per month across the whole window for each.
    recurring_merchants: dict[str, list[dict]] = {
        cat: recurring_plan.get(cat, {}).get(archetype_id, [])
        for cat in archetype.get("recurring", {})
    }

    for cat, merchants in recurring_merchants.items():
        for merchant in merchants:
            for _year, _month in WINDOW:
                emit(merchant, " (recurring)")

    # Variable: for each month, for each variable category, draw a count
    # and emit that many transactions at randomly chosen merchants from
    # the category's FULL shared pool (hit and no-hit alike).
    for year, month in WINDOW:
        for cat, spec in archetype.get("variable", {}).items():
            mean = (
                spec["monthly_mean"]
                * seasonal_multiplier(archetype, cat, month)
                * CATEGORY_FREQUENCY_BOOST.get(cat, 1.0)
            )
            count = poisson_ish(rng, mean)
            pool = catalog[cat]
            for _ in range(count):
                merchant = rng.choice(pool)
                emit(merchant, "")

    # One-time archetype-specific spikes.
    for event in archetype.get("one_time", []):
        year, month = WINDOW[event["month_index"]]
        cat = event["category"]
        pool = catalog[cat]
        for _ in range(event["count"]):
            merchant = rng.choice(pool)
            emit(merchant, " (one-time)")

    return rows


