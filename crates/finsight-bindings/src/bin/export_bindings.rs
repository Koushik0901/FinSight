//! Exports TypeScript bindings for the frontend.
//! Invoked by `cargo run -p finsight-bindings --bin export_bindings`
//! (aka `pnpm bindings`).
//!
//! The codegen contract itself — `build_specta_builder()` and every
//! `#[tauri::command]` wrapper — lives in the separate, codegen-only
//! `finsight-bindings` package. Its own `tauri_build` manifest makes this
//! Wry-linked exporter runnable on Windows without putting it in the shipped
//! `finsight-tauri` package or installer.
//! Must be run from the repo root; the output path is relative to CWD.

fn main() -> anyhow::Result<()> {
    let builder = finsight_bindings::build_specta_builder();
    builder
        .export(
            specta_typescript::Typescript::default()
                // Money lives in i64 (balance_cents); ts `number` is fine here
                // because we never exceed 2^53 cents in practice.
                .bigint(specta_typescript::BigIntExportBehavior::Number)
                .header("// AUTO-GENERATED by tauri-specta. Do not edit.\n"),
            "ui/src/api/bindings.ts",
        )
        .map_err(|e| anyhow::anyhow!("bindings export: {e}"))?;
    println!("bindings written to ui/src/api/bindings.ts");

    export_event_names()?;
    println!("event names written to ui/src/api/eventNames.ts");

    export_command_names("ui/src/api/bindings.ts")?;
    println!("command names written to ui/src/api/commandNames.ts");
    Ok(())
}

/// Emit the backend→frontend event-name contract as a TypeScript module,
/// generated from [`finsight_api::sink::event_names`] so there is exactly one
/// place that spells these strings. `finsight-server/tests/parity.rs` fails if
/// this file is stale relative to the Rust list.
fn export_event_names() -> anyhow::Result<()> {
    use finsight_api::sink::event_names;

    let ident = |name: &str| name.to_uppercase().replace(['-', ':', '.'], "_");

    let mut ts = String::from(
        "// AUTO-GENERATED by export_bindings. Do not edit.\n\
         // Source of truth: crates/finsight-api/src/sink/event_names.rs.\n\n",
    );
    for name in event_names::ALL {
        ts.push_str(&format!("export const {} = \"{name}\";\n", ident(name)));
    }
    ts.push_str("\n/** Every wire event name shared between backend and frontend. */\n");
    ts.push_str("export const EVENT_NAMES = [");
    ts.push_str(
        &event_names::ALL
            .iter()
            .map(|n| ident(n))
            .collect::<Vec<_>>()
            .join(", "),
    );
    ts.push_str("] as const;\n");
    ts.push_str("export type EventName = (typeof EVENT_NAMES)[number];\n");

    std::fs::write("ui/src/api/eventNames.ts", ts)?;
    Ok(())
}

/// Extract every `TAURI_INVOKE("cmd", …)` command name from the freshly
/// generated bindings and emit it as a TypeScript const union source
/// (`ui/src/api/commandNames.ts`). Consumers — notably the dev mock backend —
/// type themselves against this list, so a renamed or added command surfaces
/// at type-check time instead of silently falling through the mock's fallback.
fn export_command_names(bindings_path: &str) -> anyhow::Result<()> {
    let src = std::fs::read_to_string(bindings_path)?;
    let mut names: Vec<String> = Vec::new();
    for chunk in src.split("TAURI_INVOKE(\"").skip(1) {
        let name = match chunk.split('"').next() {
            Some(n) if !n.is_empty() => n.to_string(),
            _ => continue,
        };
        if !names.contains(&name) {
            names.push(name);
        }
    }
    anyhow::ensure!(
        names.len() > 100,
        "bindings parse looks broken: only { } commands found",
        names.len()
    );

    let mut ts = String::from(
        "// AUTO-GENERATED by export_bindings. Do not edit.\n\
         // The snake_case wire name of every RPC command, in bindings order.\n\n",
    );
    ts.push_str("export const COMMAND_NAMES = [\n");
    for n in &names {
        ts.push_str(&format!("  \"{n}\",\n"));
    }
    ts.push_str("] as const;\n");
    ts.push_str("export type CommandName = (typeof COMMAND_NAMES)[number];\n");

    std::fs::write("ui/src/api/commandNames.ts", ts)?;
    Ok(())
}
